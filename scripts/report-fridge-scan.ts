// Writes testing/fridge-scan/RESULTS.md from the saved evaluation runs: for
// each photo, what a person saw beside what each model said, so the scores
// can be checked by eye.
//
//   node scripts/report-fridge-scan.ts

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Row {
  photo: string;
  ms: number;
  found: { name: string; count: number | null; confidence: string }[];
  recall: number;
  precision: number;
  matched: string[];
  missed: string[];
  wrong: string[];
}
interface Run {
  model: string;
  recall: number;
  precision: number;
  meanMs: number;
  rows: Row[];
}

const dir = "testing/fridge-scan";
const truth = JSON.parse(readFileSync(join(dir, "truth.json"), "utf8")) as Record<string, { required: Record<string, string[]>; acceptable: string[] }>;
const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")) as { file: string; source_page: string; license: string }[];
const runs = readdirSync(join(dir, "results"))
  .filter((f) => f.endsWith(".json") && !/-\d\d\.json$/.test(f))
  .map((f) => JSON.parse(readFileSync(join(dir, "results", f), "utf8")) as Run)
  .sort((a, b) => b.recall - a.recall);

const pct = (n: number) => `${Math.round(n * 100)}%`;
const lines: string[] = [];
lines.push("# Fridge photo scan: test results", "");
lines.push("Generated by `scripts/report-fridge-scan.ts` from `results/*.json`. Each model ran the app's own prompt and parser (`src/fridge-scan.ts`) on the same 12 photos.", "");
lines.push("**How it's scored.** For each photo I listed the items a careful person can see (*required*) and items that might be there but can't be confirmed (*acceptable*, e.g. an unlabelled tub that could be hummus or dip). **Recall** is the share of required items the model found. **Precision** is the share of the model's suggestions that are required or acceptable; the rest are listed as *wrong*. Matching is by keyword, so \"pear\" counts for the pear and \"chicken\" counts for raw chicken; see `truth.json` for the exact keywords.", "");
lines.push("## Summary", "");
lines.push("| Model | Recall | Precision | Mean time / photo |", "|---|---|---|---|");
for (const r of runs) lines.push(`| ${r.model} | ${pct(r.recall)} | ${pct(r.precision)} | ${(r.meanMs / 1000).toFixed(0)} s |`);
lines.push("", "## Photo by photo", "");
for (const photo of Object.keys(truth)) {
  const t = truth[photo];
  const m = manifest.find((x) => x.file === photo);
  lines.push(`### ${photo}`, "");
  lines.push(`![${photo}](${photo})`, "");
  if (m) lines.push(`Source: ${m.source_page} (${m.license})`, "");
  lines.push(`**What I saw (required):** ${Object.keys(t.required).join(", ")}`, "");
  for (const r of runs) {
    const row = r.rows.find((x) => x.photo === photo);
    if (!row) continue;
    lines.push(`**${r.model}** — recall ${pct(row.recall)}, precision ${pct(row.precision)}, ${(row.ms / 1000).toFixed(0)} s`, "");
    lines.push(`- Said: ${row.found.map((f) => `${f.name}${f.count ? ` ×${f.count}` : ""}${f.confidence === "low" ? " (guess)" : ""}`).join(", ") || "*nothing*"}`);
    lines.push(`- Missed: ${row.missed.join(", ") || "—"}`);
    lines.push(`- Wrong: ${row.wrong.join(", ") || "—"}`, "");
  }
}
writeFileSync(join(dir, "RESULTS.md"), lines.join("\n"));
console.log(`wrote ${join(dir, "RESULTS.md")} from ${runs.length} run(s)`);
